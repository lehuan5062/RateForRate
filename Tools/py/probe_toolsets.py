"""Runtime check of the MCP toolset register and of what the Python API exposes (UE 5.8).

Dumps every registered toolset and tool (unreal.ToolsetRegistry), writes Docs/mcp-toolsets.md, checks that no audio toolset exists,
and records `hasattr(unreal, X)` for the classes the game relies on.
Run: Tools\\run_py.ps1 -Script Tools\\py\\probe_toolsets.py
"""
import json
import os
import sys

import unreal

sys.path.append(os.path.join(unreal.SystemLibrary.get_project_directory(), "Tools", "py"))
from shift_common import PROJECT_DIR, finish, log, stage, warn  # noqa: E402

OUT_DOC = os.path.join(PROJECT_DIR, "Docs", "mcp-toolsets.md")

EXPOSURE = [
    "ToolsetRegistry", "GameFeaturesSubsystem", "GameFeatureData", "StateTree", "StateTreeEditorData", "StateTreeState",
    "StateTreeEditingSubsystem", "StateTreeFactory", "MetaSoundBuilderSubsystem", "MetaSoundEditorSubsystem", "MetaSoundSource",
    "MetaSoundPatch", "MetaSoundOutputSubsystem", "MidiStepSequence", "MusicClockComponent", "MetaSoundSourceBuilder", "MetaSoundPatchBuilder",
    "GameplayTagsManager", "GameplayAbility", "AbilitySystemComponent", "MassEntitySubsystem", "MassSpawnerSubsystem",
]


@stage("toolset register")
def toolsets():
    reg = getattr(unreal, "ToolsetRegistry", None)
    if reg is None:
        raise RuntimeError("unreal.ToolsetRegistry is not exposed")
    log("ToolsetRegistry members: {}".format([n for n in dir(reg) if not n.startswith("_")]))
    raw = reg.get_all_toolset_json_schemas()
    log("get_all_toolset_json_schemas -> {} ({} chars)".format(type(raw), len(str(raw))))
    return raw


def parse(raw):
    """Normalise whatever the registry returned into {toolset: [(tool, description)]}."""
    data = raw
    if isinstance(raw, str):
        data = json.loads(raw)
    result = {}

    def add(toolset, tool, desc):
        result.setdefault(toolset, []).append((tool, (desc or "").strip().split("\n")[0][:140]))

    if isinstance(data, dict):
        items = data.items()
    elif isinstance(data, (list, tuple)):
        items = []
        for entry in data:
            if isinstance(entry, str):
                try:
                    entry = json.loads(entry)
                except ValueError:
                    continue
            if isinstance(entry, dict):
                items.append((entry.get("name") or entry.get("toolset") or entry.get("toolset_name") or "?", entry))
    else:
        items = []
    for name, body in items:
        tools = []
        if isinstance(body, dict):
            tools = body.get("tools") or body.get("functions") or []
        if isinstance(tools, dict):
            tools = [dict(v, name=k) if isinstance(v, dict) else {"name": k} for k, v in tools.items()]
        for tool in tools:
            if isinstance(tool, dict):
                add(name, tool.get("name") or tool.get("tool_name") or "?", tool.get("description"))
            else:
                add(name, str(tool), "")
        if not tools:
            add(name, "(schema only)", "")
    return result


def write_doc(reg):
    total = sum(len(v) for v in reg.values())
    audio = [n for n in reg if any(k in n.lower() for k in ("audio", "sound", "metasound", "harmonix", "music"))]
    lines = [
        "# MCP toolsets in UE 5.8 (runtime-probed)",
        "",
        "Generated by `Tools/py/probe_toolsets.py` from `unreal.ToolsetRegistry.get_all_toolset_json_schemas()` (do not edit by hand).",
        "",
        "{} toolsets, {} tools. Audio / MetaSound / Harmonix toolsets: {}.".format(len(reg), total, ", ".join(audio) if audio else "none"),
        "",
    ]
    for name in sorted(reg):
        lines.append("## {} ({})".format(name, len(reg[name])))
        lines.append("")
        for tool, desc in sorted(reg[name]):
            lines.append("- `{}`{}".format(tool, " - " + desc if desc else ""))
        lines.append("")
    with open(OUT_DOC, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    log("wrote {}: {} toolsets, {} tools, audio toolsets: {}".format(OUT_DOC, len(reg), total, audio or "none"))
    return audio


@stage("python exposure")
def exposure():
    for name in EXPOSURE:
        log("hasattr(unreal, {!r}) = {}".format(name, hasattr(unreal, name)))
    st_ed = getattr(unreal, "StateTreeEditorData", None)
    if st_ed:
        log("StateTreeEditorData members: {}".format([n for n in dir(st_ed) if not n.startswith("_")][:40]))
    sub = getattr(unreal, "StateTreeEditingSubsystem", None)
    if sub:
        log("StateTreeEditingSubsystem members: {}".format([n for n in dir(sub) if not n.startswith("_")][:40]))
    gf = getattr(unreal, "GameFeaturesSubsystem", None)
    if gf:
        log("GameFeaturesSubsystem members: {}".format([n for n in dir(gf) if not n.startswith("_")][:40]))
    mc = getattr(unreal, "MetaSoundOutputSubsystem", None)
    if mc:
        log("MetaSoundOutputSubsystem members: {}".format([n for n in dir(mc) if not n.startswith("_")][:40]))
    names = sorted(n for n in dir(unreal) if "harmonix" in n.lower() or "musicclock" in n.lower() or "midi" in n.lower())
    log("Harmonix/Midi names ({}): {}".format(len(names), ", ".join(names)))


def main():
    raw = toolsets()
    if raw is not None:
        reg = parse(raw)
        write_doc(reg)
    exposure()
    finish()


main()
